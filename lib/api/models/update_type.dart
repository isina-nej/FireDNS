/// انواع آپدیت برنامه
enum UpdateType {
  /// آپدیت اجباری - کاربر نمی‌تواند از برنامه استفاده کند
  mandatory,

  /// آپدیت مهم - کاربر می‌تواند از برنامه استفاده کند اما هر بار به صفحه آپدیت هدایت می‌شود
  important,

  /// آپدیت جزئی - فقط اطلاع‌رسانی می‌شود و کاربر می‌تواند از برنامه استفاده کند
  minor,
}